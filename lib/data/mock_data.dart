  /// Produces a gently curved line between two points so sample routes are
  /// visually distinguishable on the map.
  static List<LatLng> _curve(LatLng start, LatLng end, double bend) {
    const int steps = 40;
    final double dLat = end.latitude - start.latitude;
    final double dLon = end.longitude - start.longitude;
    final List<LatLng> points = <LatLng>[];

    for (int i = 0; i <= steps; i++) {
      final double t = i / steps;
      // Peaks in the middle of the line and vanishes at both ends.
      final double offset = bend * (t * (1 - t) * 4);
      points.add(
        LatLng(
          start.latitude + dLat * t - dLon * offset,
          start.longitude + dLon * t + dLat * offset,
        ),
      );
    }
    return points;
  }
