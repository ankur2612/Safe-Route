  static List<LocationModel> searchPlaces(String query) {
    final String needle = query.trim().toLowerCase();
    if (needle.isEmpty) return const <LocationModel>[];
    return places.where((LocationModel place) {
      return place.name.toLowerCase().contains(needle) ||
          (place.address?.toLowerCase().contains(needle) ?? false);
    }).toList(growable: false);
  }

  /// Builds three plausible route options between two points.
  ///
  /// The geometry is generated by bending the straight line between start and
  /// destination so the routes look distinct on the map. Real geometry will
  /// come from OSRM through the backend.
  static RouteResultModel routes({
    required LatLng start,
    required LatLng destination,
    required RoutePreference preference,
  }) {
    final double directKm = const Distance().distance(start, destination) / 1000;
    // Keep the sample usable even when start and destination are very close.
